SENTENCES: tuple[Row, ...] = (*KINDS["opt"], *_LABELS, *_CONFIDENCE, *_MOVES)

# ---------------------------------------------------------------- matcher

_PH = re.compile(r"\{(\w+)(?::([\w*]+))?\}")
_ANY = r".+?"
_WORD = r"(?:(?!\.\s).)+?"  # a copied part never spans a sentence end
_SPLIT = re.compile(r"(?<=[.!?])\s+(?=[A-Z“\"£0-9])")


def _literal_len(template: str) -> int:
    return len(_PH.sub("", template))


@cache
def _kind_regex(kind: str) -> str:
    alts = sorted((r[0] for r in KINDS[kind]), key=lambda t: -_literal_len(t))
    return "(?:" + "|".join(_template_regex(t, named=False) for t in alts) + ")"


def _template_regex(template: str, named: bool) -> str:
    out: list[str] = []
    pos = 0
    for m in _PH.finditer(template):
        out.append(re.escape(template[pos:m.start()]))
        name, kind = m.group(1), m.group(2)
        body = _WORD if kind is None else _ANY if kind == "*" else _kind_regex(kind)
        out.append(f"(?P<{name}>{body})" if named else f"(?:{body})")
        pos = m.end()
    out.append(re.escape(template[pos:]))
    return "".join(out)


@cache
def _compiled(rows_id: str) -> tuple[tuple[re.Pattern[str], Row, dict[str, str | None]], ...]:
    rows = SENTENCES if rows_id == "*" else KINDS[rows_id]
    order = sorted(rows, key=lambda r: -_literal_len(r[0]))
    out = []
    for r in order:
        kinds = {m.group(1): m.group(2) for m in _PH.finditer(r[0])}
        out.append((re.compile(_template_regex(r[0], named=True), re.DOTALL), r, kinds))
    return tuple(out)


def _fill(template: str, values: dict[str, str]) -> str:
    return _PH.sub(lambda m: values[m.group(1)], template)


def _match(text: str, rows_id: str, lang: str) -> str | None:
    i = LANGS.index(lang)
    for rx, row, kinds in _compiled(rows_id):
        m = rx.fullmatch(text)
        if m is None:
            continue
        values: dict[str, str] = {}
        for name, kind in kinds.items():
            part = m.group(name)
            if kind is None:
                values[name] = part
                continue
            done = translate_text(part, lang) if kind == "*" else _match(part, kind, lang)
            if done is None:
                break
            values[name] = done
        else:
            return _fill(row[i], values)
    return None


def _cap(text: str, lang: str) -> str:
    return text[:1].upper() + text[1:] if lang in LATIN and text[:1].islower() else text


def translate_text(text: str, language: str | None) -> str | None:
    """The text in `language`, or None when a part of it matches no template. English returns the text."""
    lang = language_of(language)
    if lang == "en" or not text:
        return text
    whole = _match(text, "*", lang)
    if whole is not None:
        return _cap(whole, lang)
    parts = _SPLIT.split(text)
    if len(parts) < 2:
        return None
    done = [_match(p, "*", lang) for p in parts]
    if any(d is None for d in done):
        return None
    return ("" if lang == "zh-Hans" else " ").join(_cap(d, lang) for d in done if d is not None)


# ---------------------------------------------------------------- moves

# Field limits from the contract: a translation that does not fit keeps the English text.
_LIMITS = {"summary": 90, "reason": 140, "confidence_text": 140}


def _tr(text: str | None, lang: str, limit: int | None = None) -> str | None:
    if text is None:
        return None
    done = translate_text(text, lang)
    if done is None or (limit is not None and len(done) > limit):
        return text
    return done


def translate_move(move: Move, language: str | None) -> Move:
    """Every user-facing text of the move in `language`. Numbers, facts, ids and sources are unchanged."""
    lang = language_of(language)
    if lang == "en":
        return move
    data: dict[str, Any] = move.model_dump(mode="python")
    for key in ("action", "headline", "confidence_label"):
        data[key] = _tr(data[key], lang)
    for key in ("reason", "confidence_text"):
        data[key] = _tr(data[key], lang, _LIMITS[key])
    for e in data["evidence"]:
        e["text"] = _tr(e["text"], lang)
    for o in data["options"]:
        o["label"] = _tr(o["label"], lang)
    if data.get("test_period"):
        data["test_period"]["label"] = _tr(data["test_period"]["label"], lang)
    if data.get("trade_off"):
        data["trade_off"]["summary"] = _tr(data["trade_off"]["summary"], lang, _LIMITS["summary"])
        for p in data["trade_off"]["points"]:
            p["text"] = _tr(p["text"], lang)
    return Move.model_validate(data)


def translate_response(resp: NextMoveResponse, language: str | None) -> NextMoveResponse:
    """The response with every move and context line in `language`; English is returned unchanged."""
    lang = language_of(language)
    if lang == "en":
        return resp
    return resp.model_copy(update={
        "top": translate_move(resp.top, lang),
        "runners_up": [translate_move(m, lang) for m in resp.runners_up],
        "context_lines": [_tr(t, lang) or t for t in resp.context_lines],
    })


def untranslated(texts: Iterable[str], language: str) -> list[str]:
    """The texts that match no template in `language` (for tests and logs)."""
    return [t for t in texts if translate_text(t, language) is None]
