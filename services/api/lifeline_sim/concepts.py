_BY_ID = {c.id: c for c in CONCEPTS}


def concept_ids() -> list[str]:
    return [c.id for c in CONCEPTS]


def build_lesson(
    concept_id: str, mv: MacroView | None, year: int = p.PRESENT_YEAR, region: str | None = None
) -> Lesson:
    c = _BY_ID[concept_id]
    points: list[ChartPoint] = []
    source = None
    if mv is not None and mv.has(c.chart_key):
        for y in range(year - CHART_YEARS + 1, year + 1):
            v = mv.get(c.chart_key, y, region)
            if v is None or v.year != y:
                continue  # skip years filled by the nearest-year rule
            points.append(ChartPoint(x=float(y), y=round(v.value, 2)))
        source = mv.source_ref(c.chart_key, year, region)
    return Lesson(
        concept_id=c.id,
        title=c.lesson_title,
        chart=Chart(kind="line", title=c.chart_title, x_label="Year", y_label=c.y_label, points=points, source=source),
        sentences=list(c.sentences),
        quiz=Quiz(question=c.question, options=list(c.options), answer_index=c.answer_index),
    )


def build_concept(concept_id: str, mv: MacroView | None, year: int = p.PRESENT_YEAR) -> Concept:
    c = _BY_ID[concept_id]
    return Concept(
        id=c.id, title=c.title, emoji=c.emoji, area=c.area, summary=c.summary, lesson=build_lesson(c.id, mv, year)
    )
