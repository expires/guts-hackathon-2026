"""Learn course content (ADR 0068). Pure data, no I/O. Text is fixed and written by hand, not AI generated.

Six units in student-lifecycle order. Every Life game concept (`lifeline_sim.concepts`) is taught by exactly one
lesson (`concept`). Every fact names a rule in the facts table (`lifeline_engine.rules`); the number in the fact
text is that rule's value, so each number traces to its official source and checked date.

Quiz answers: `answer` is the index of the right choice. Choice ids are "a".."d" by position.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class QSpec:
    text: str
    choices: tuple[str, ...]
    answer: int
    why: str


@dataclass(frozen=True)
class FactSpec:
    rule: str  # id in lifeline_engine.rules, without the "rule." prefix
    text: str


@dataclass(frozen=True)
class LessonSpec:
    id: str
    title: str
    icon: str  # SF Symbol name
    concept: str | None
    cards: tuple[tuple[str, str], ...]
    facts: tuple[FactSpec, ...]
    quiz: tuple[QSpec, ...]


@dataclass(frozen=True)
class UnitSpec:
    id: str
    title: str
    description: str
    lessons: tuple[LessonSpec, ...]


def _l(
    id_: str,
    title: str,
    icon: str,
    concept: str | None,
    cards: list[tuple[str, str]],
    facts: list[tuple[str, str]],
    quiz: list[tuple[str, tuple[str, ...], int, str]],
) -> LessonSpec:
    return LessonSpec(
        id=id_, title=title, icon=icon, concept=concept, cards=tuple(cards),
        facts=tuple(FactSpec(rule=r, text=t) for r, t in facts),
        quiz=tuple(QSpec(text=q, choices=c, answer=a, why=w) for q, c, a, w in quiz),
    )


